// Binary Search Trees
import java.util.TreeMap;

public class BSTExample {
    
    public static void main(String[] args) {
        
        TreeMap<Integer, String> students = new TreeMap<>();

        students.put(3, "Chris");
        students.put(1, "Alex");
        students.put(2, "Sam");

        System.out.println(students);
    }
}
