public class DoubleExample {
    public static void main(String[] args) {

        // Store a decimal number
        double price = 19.99;

        // Print the price
        System.out.println(price);

        // Store two decimal numbers
        double x = 5.5;
        double y = 2.0;

        // Multiply the numbers
        double answer = x * y;

        // Print answer
        System.out.println(answer);
    }
}
