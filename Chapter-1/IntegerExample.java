public class IntegerExample {
    public static void main(String[] args) {

        // Store two whole numbers
        int x = 10;
        int y = 5;
        int z = 3;

        // Add the numbers
        int answer = x + y;

        // Print the answer
        System.out.println(answer);

        // Find the remainder
        int remainder = x % z;

        // Pring the answer
        System.out.println(remainder);
    }

}
